// Phase 1 through the browser, real stack (Keycloak → nginx SPA → FastAPI as avenel_app → PostgreSQL).
// No interception (Part K 26). Every API request is logged by recordApiTraffic.
import { mkdirSync } from 'node:fs';
import { expect, test, type Page } from '@playwright/test';
import { API_ORIGIN, CLIENT_USER, loginThroughKeycloak, recordApiTraffic, seed } from './stack';

const SHOTS = 'docs/reports/phase-1';
// The client-user test needs the id read by the accountant test: run in order, in one worker.
test.describe.configure({ mode: 'serial' });
mkdirSync(SHOTS, { recursive: true });

function bearerOf(page: Page): () => string {
  let bearer = '';
  page.on('request', (r) => {
    const a = r.headers()['authorization'];
    if (r.url().startsWith(API_ORIGIN) && a) bearer = a;
  });
  return () => bearer;
}

test('accountant: create company, open period, overlap refused, CGNC + file import, DPA/CNDP', async ({ page, request }) => {
  const log = recordApiTraffic(page, 'phase1-accountant');
  const bearer = bearerOf(page);
  await loginThroughKeycloak(page);

  // Clients list from GET /v1/client-entities
  await page.getByRole('link', { name: 'Clients' }).click();
  await expect(page.getByTestId('client-row')).toHaveCount(seed.clients.length);

  // Create a company (synthetic name and ICE, unique per run)
  const stamp = Date.now().toString().slice(-9);
  const name = `Société E2E ${stamp}`;
  await page.getByTestId('btn-new-client').click();
  await page.locator('input[name="legal_name"]').fill(name);
  await page.locator('input[name="ice"]').fill(`009${stamp}000`.slice(0, 15));
  await page.getByRole('button', { name: 'Créer la société' }).click();
  await expect(page.getByTestId('clients-table')).toContainText(name);
  await page.screenshot({ path: `${SHOTS}/01-clients.png`, fullPage: true });

  // Company page
  await page.getByRole('link', { name }).click();
  await expect(page.getByTestId('client-name')).toHaveText(name);

  // Open a period; the fiscal year end is entered by the user, never defaulted
  await page.locator('input[name="period_code"]').fill('2026-10');
  await page.locator('input[name="fiscal_year_end"]').fill('2026-12-31');
  await page.getByTestId('btn-open-period').click();
  await expect(page.getByTestId('msg-ok')).toContainText('Période 2026-10 ouverte.');
  await expect(page.getByTestId('period-row')).toHaveCount(1);

  // Same period again: the API refuses (overlap protection); the UI shows the API's message
  await page.locator('input[name="period_code"]').fill('2026-10');
  await page.getByTestId('btn-open-period').click();
  await expect(page.getByTestId('msg-error')).toBeVisible();
  await expect(page.getByTestId('period-row')).toHaveCount(1);

  // Seed CGNC chart, then import a CSV file through the hardened server parser
  await page.getByTestId('btn-seed-cgnc').click();
  await expect(page.getByTestId('chart-count')).toBeVisible();
  const before = Number((await page.getByTestId('chart-count').textContent())?.split(' ')[0]);
  expect(before).toBeGreaterThan(0);
  await page.getByTestId('input-chart-file').setInputFiles({
    name: 'plan-societe.csv',
    mimeType: 'text/csv',
    buffer: Buffer.from('code;label\n61119;Achats de marchandises E2E\n'),
  });
  await expect(page.getByTestId('msg-ok')).toContainText('comptes importés');
  await page.screenshot({ path: `${SHOTS}/02-client-periods-chart.png`, fullPage: true });

  // Compliance documents generated by the API
  await page.getByRole('link', { name: 'Paramètres' }).click();
  await expect(page.getByTestId('doc-dpa')).toBeVisible();
  await page.screenshot({ path: `${SHOTS}/03-dpa.png`, fullPage: true });
  await page.getByTestId('tab-cndp').click();
  await expect(page.getByTestId('doc-cndp')).toBeVisible();

  for (const p of [
    'GET http://localhost:8000/v1/client-entities -> 200',
    'POST http://localhost:8000/v1/client-entities -> 201',
    '/periods -> 201',
    '/periods -> 409',
    '/chart-accounts/seed-cgnc -> 200',
    '/chart-accounts/import-file -> 200',
    'GET http://localhost:8000/v1/compliance/dpa -> 200',
    'GET http://localhost:8000/v1/compliance/cndp-dossier -> 200',
  ]) {
    // Response events reach the test asynchronously; wait for the logged call instead of racing it.
    await expect.poll(() => log.some((l) => l.includes(p)), { message: `expected API call: ${p}` }).toBe(true);
  }

  // Keep the out-of-scope company id for the client-user test, read with the accountant's own token
  const list = await request.get(`${API_ORIGIN}/v1/client-entities`, { headers: { Authorization: bearer() } });
  const items = ((await list.json()) as { items: { id: string; legal_name: string }[] }).items;
  const other = items.find((c) => c.legal_name !== seed.client_user.scoped_to && seed.clients.some((s) => s.legal_name === c.legal_name));
  expect(other).toBeTruthy();
  process.env.E2E_OUT_OF_SCOPE_CLIENT = other!.id;
  await page.getByTestId('btn-logout').click();
  await page.waitForURL((u) => u.pathname === '/');
});

test('client user sees only the company in scope (browser and API)', async ({ page, request }) => {
  const log = recordApiTraffic(page, 'phase1-client-user');
  const bearer = bearerOf(page);
  await loginThroughKeycloak(page, { username: CLIENT_USER });

  // Queue: only the scoped company's monthly file
  await expect(page.getByTestId('queue-row')).toHaveCount(1);
  await expect(page.getByTestId('queue-table')).toContainText(seed.client_user.scoped_to);

  // Clients: only the scoped company, and no create action
  await page.getByRole('link', { name: 'Clients' }).click();
  await expect(page.getByTestId('client-row')).toHaveCount(1);
  await expect(page.getByTestId('clients-table')).toContainText(seed.client_user.scoped_to);
  await expect(page.getByTestId('btn-new-client')).toHaveCount(0);
  await page.screenshot({ path: `${SHOTS}/04-client-user-clients.png`, fullPage: true });

  // Through the API with the client user's own token: the other company is 404, not 403
  const all = await request.get(`${API_ORIGIN}/v1/client-entities`, { headers: { Authorization: bearer() } });
  const items = ((await all.json()) as { items: { id: string; legal_name: string }[] }).items;
  expect(items.map((c) => c.legal_name)).toEqual([seed.client_user.scoped_to]);
  const otherId = process.env.E2E_OUT_OF_SCOPE_CLIENT;
  expect(otherId, 'out-of-scope company id from the accountant test').toBeTruthy();
  const res = await request.get(`${API_ORIGIN}/v1/client-entities/${otherId}`, { headers: { Authorization: bearer() } });
  console.log(`[phase1-client-user] direct GET ${API_ORIGIN}/v1/client-entities/${otherId} -> ${res.status()}`);
  expect(res.status()).toBe(404);
  // The UI shows the not-found state for the same id. Client-side navigation: a full reload
  // would drop the in-memory tokens by design.
  await page.evaluate((path) => {
    window.history.pushState({}, '', path);
    window.dispatchEvent(new PopStateEvent('popstate'));
  }, `/clients/${otherId}`);
  await expect(page.getByText('Société introuvable.')).toBeVisible();
  // Compliance documents are refused to client users by the API; the UI does not request them
  await page.getByRole('link', { name: 'Paramètres' }).click();
  await expect(page.getByText('Ces documents sont réservés au cabinet.')).toBeVisible();
  await expect.poll(() => log.some((l) => l.includes('GET http://localhost:8000/v1/client-entities -> 200'))).toBe(true);
});
